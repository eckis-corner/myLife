def build() -> dict[str, tuple[str, str]]:
    texts = dict(TEXTS)
    catalog = catalog_texts.load()
    duplicates = sorted(set(texts) & set(catalog))
    if duplicates:
        raise SystemExit(f"Doppelte Schlüssel mit dem Katalog: {duplicates}")
    texts.update(catalog)
    return texts
