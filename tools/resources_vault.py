def build() -> dict[str, tuple[str, str]]:
    texts = dict(TEXTS)
    for number, (name, text) in AREAS.items():
        texts[f"Area_{number}"] = name
        texts[f"AreaText_{number}"] = text
    for key, value in TYPES.items():
        texts[f"Type_{key}"] = value
    for key, value in EXPIRY.items():
        texts[f"Expiry_{key}"] = value
    for key, value in FIELDS.items():
        texts[f"Field_{key}"] = value
    for (type_key, field), value in FIELD_OVERRIDES.items():
        texts[f"Field_{type_key}_{field}"] = value
    for key, value in HINTS.items():
        texts[f"FieldHint_{key}"] = value
    for option_set, values in OPTIONS.items():
        for key, value in values.items():
            texts[f"Option_{option_set}_{key}"] = value
    return texts
